"""
실습 1: 간단한 계산기

두 수를 입력받아 사칙연산(+, -, *, /) 결과를 모두 출력하세요.
"""

a = int(input("첫 번째 수: "))
b = int(input("두 번째 수: "))

# 아래에 사칙연산 결과를 출력하세요
# 두수를 더한 사칙연산  
print("더하기:", a + b)
# 두수를 뺀 사칙연산
print("빼기:", a - b)
# 두수를 곱한 사칙연산
print("곱하기:", a * b) 
# 두수를 나눈 사칙연산
print("나누기:", a / b) 


